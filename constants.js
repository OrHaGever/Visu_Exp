export function inferSupplierSub(name = "") {
  const n = name.toLowerCase();

  if (n.includes("חשמל") || n.includes("גז") || n.includes("אמישרגז") || n.includes("וינטר"))
    return "חשמל / מים / גז";
  if (n.includes("ארנונה"))
    return "מיסים וארנונה";
  if (n.includes("בזק") || n.includes("אינטרנט") || n.includes("מש-נט") || n.includes("אייפרקטיקום"))
    return "תקשורת ואינטרנט";
  if (n.includes("ישראכרט") || n.includes("מקס"))
    return "עמלות וסליקה";
  if (n.includes("וולט") || n.includes("משלוחה"))
    return "משלוחים ופלטפורמות";
  if (n.includes("יין") || n.includes("היכל היין"))
    return "יין";
  if (n.includes("שתייה") || n.includes("החברה המרכזית") || n.includes("סוקליק"))
    return "שתייה קלה";
  if (n.includes("קינוחים") || n.includes("ביסקוטי") || n.includes("אייס דרים"))
    return "קינוחים";
  if (n.includes("פרחים"))
    return "פרחים ועיצוב";
  if (n.includes("שיווק") || n.includes("דגים") || n.includes("מזון") || n.includes("פרוט") || n.includes("חקלאיים") || n.includes("לה פסטה") || n.includes("טעם הארץ") || n.includes("סוגת"))
    return "דגים";

  return "לא משויך";
}